const CATEGORY_METADATA_BY_PATH = new Map(
  CATEGORY_METADATA_DEFINITIONS.map(
    ([path, partAttribute, engineers, coveredParts]) => {
      const sortNo = CATEGORY_SOURCE_SORT_NO_BY_PATH.get(path);

      if (sortNo === undefined) {
        throw new Error(`缺少成本分析分类源序号：${path}`);
      }

      return [
        path,
        {
          sortNo,
          partAttribute,
          engineers,
          coveredParts,
        },
      ] as const;
    },
  ),
);

const createLevelThreeNodes = (
  parentId: string,
  parentCode: string,
  parentPath: string,
  parts: readonly PartDefinition[],
): CostAnalysisCategoryNode[] =>
  parts.map(([key, code, name]) => {
    const path = `${parentPath}/${name}`;
    const metadata = CATEGORY_METADATA_BY_PATH.get(path);

    if (!metadata) {
      throw new Error(`缺少成本分析分类元数据：${path}`);
    }

    return {
      id: `l3-${parentId.slice(3)}-${key}`,
      parentId,
      level: 3,
      code: `${parentCode}_${code}`,
      name,
      path,
      sortNo: metadata.sortNo,
      partAttribute: metadata.partAttribute,
      engineers: [...metadata.engineers],
      coveredParts: [...metadata.coveredParts],
      children: [],
    };
  });

const createLevelTwoNodes = (
  parentKey: string,
  parentId: string,
  parentCode: string,
  parentPath: string,
  categories: readonly CategoryDefinition[],
): CostAnalysisCategoryNode[] =>
  categories.map(([key, code, name, parts], index) => {
    const id = `l2-${parentKey}-${key}`;
    const path = `${parentPath}/${name}`;
    const nodeCode = `${parentCode}_${code}`;

    return {
      id,
      parentId,
      level: 2,
      code: nodeCode,
      name,
      path,
      sortNo: index + 1,
      children: createLevelThreeNodes(id, nodeCode, path, parts),
    };
  });

const createLevelOneNode = (
  key: string,
  code: string,
  name: string,
  sortNo: number,
  categories: readonly CategoryDefinition[],
): CostAnalysisCategoryNode => {
  const id = `l1-${key}`;

  return {
    id,
    parentId: null,
    level: 1,
    code,
    name,
    path: name,
    sortNo,
    children: createLevelTwoNodes(key, id, code, name, categories),
  };
};

